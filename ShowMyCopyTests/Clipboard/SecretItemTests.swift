@testable import ShowMyCopy

struct PasteboardMarkerTests {
    @Test func passwordMarkersAreSecretNotAlwaysSkipped() {
        let passwordMarkers: Set<String> = [
            PasteboardMarker.concealed, "com.agilebits.onepassword", "net.antelle.keeweb",
        ]
        #expect(PasteboardMarker.secret == passwordMarkers)
        #expect(PasteboardMarker.secret.isDisjoint(with: PasteboardMarker.alwaysSkipped))
    }

    @Test func transientAndGeneratedMarkersAreAlwaysSkipped() {
        #expect(
            PasteboardMarker.alwaysSkipped == [
                PasteboardMarker.transient, PasteboardMarker.autoGenerated,
                "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
            ]
        )
    }

    @Test func legacyMarkersAreAllSortedIntoAGroup() {
        #expect(PasteboardMarker.legacy.isSubset(of: PasteboardMarker.secret.union(PasteboardMarker.alwaysSkipped)))
    }
}

struct PasswordManagerTests {
    @Test(arguments: [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "org.keepassxc.keepassxc",
        "com.markmcguill.strongbox.mac",
        "com.markmcguill.strongbox.mac.pro",
        "com.lastpass.LastPass",
        "com.lastpass.lastpassmacdesktop",
        "me.proton.pass.electron",
        "in.sinew.Enpass-Desktop",
        "in.sinew.Enpass-Desktop.App",
        "com.keepersecurity.passwordmanager",
    ])
    func knowsPasswordManager(bundleIdentifier: String) {
        #expect(PasswordManager.isPasswordManager(bundleIdentifier: bundleIdentifier))
    }

    @Test func ignoresLetterCase() {
        #expect(PasswordManager.isPasswordManager(bundleIdentifier: "COM.BITWARDEN.DESKTOP"))
    }

    @Test(arguments: [
        "com.apple.Notes",
        "com.apple.Safari",
        "com.bitwarden.desktopx",
        "com.markmcguill.strongboxed",
        "com.lastpassword.app",
        "",
    ])
    func otherAppsAreNotPasswordManagers(bundleIdentifier: String) {
        #expect(!PasswordManager.isPasswordManager(bundleIdentifier: bundleIdentifier))
    }

    @Test func unknownAppIsNotAPasswordManager() {
        #expect(!PasswordManager.isPasswordManager(bundleIdentifier: nil))
    }
}

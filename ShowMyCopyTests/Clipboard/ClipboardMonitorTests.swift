@MainActor
struct ClipboardMonitorTests {
    private let pasteboard = FakePasteboard()
    private let history = ClipboardHistory()
    private let date = Date(timeIntervalSince1970: 1_790_000_000)
    private let notes = SourceApp(bundleIdentifier: "com.apple.Notes", name: "Notes")

    private func makeMonitor() -> ClipboardMonitor {
        ClipboardMonitor(
            pasteboard: pasteboard,
            history: history,
            frontmostApp: { [notes] in notes },
            now: { [date] in date }
        )
    }

    @Test func recordsWhatIsOnThePasteboardAtLaunch() {
        pasteboard.copy("already copied")
        makeMonitor().poll()
        #expect(history.entries.map(\.text) == ["already copied"])
        #expect(history.entries.first?.sourceApp == nil)
    }

    @Test func recordsNewCopyWithSourceAppAndTime() throws {
        let monitor = makeMonitor()
        monitor.poll()
        pasteboard.copy("hello")
        monitor.poll()

        let entry = try #require(history.entries.first)
        #expect(entry.text == "hello")
        #expect(entry.sourceApp == notes)
        #expect(entry.date == date)
    }

    @Test func doesNotReadContentsWhenChangeCountIsTheSame() {
        let monitor = makeMonitor()
        pasteboard.copy("first")
        monitor.poll()
        pasteboard.text = "changed without a new copy"
        monitor.poll()
        #expect(history.entries.map(\.text) == ["first"])
    }

    @Test(
        arguments: [PasteboardMarker.concealed, PasteboardMarker.transient, PasteboardMarker.autoGenerated]
            + PasteboardMarker.legacy.sorted()
    )
    func skipsMarkedItems(marker: String) {
        let monitor = makeMonitor()
        pasteboard.copy("secret", markers: [marker])
        monitor.poll()
        #expect(history.entries.isEmpty)
    }

    @Test func skipsConcealedItemWrittenWhileTheTextIsRead() {
        let monitor = makeMonitor()
        monitor.poll()
        pasteboard.copy("plain text")
        // A password manager replaces the item after the monitor checked the markers but before it read the text.
        pasteboard.whileReadingString = { $0.copy("secret", markers: [PasteboardMarker.concealed]) }
        monitor.poll()
        #expect(history.entries.isEmpty)

        monitor.poll()
        #expect(history.entries.isEmpty)
    }

    @Test func readsAgainOnNextPollWhenThePasteboardChangedDuringTheRead() {
        let monitor = makeMonitor()
        monitor.poll()
        pasteboard.copy("first")
        pasteboard.whileReadingString = { $0.copy("second") }
        monitor.poll()
        #expect(history.entries.isEmpty)

        monitor.poll()
        #expect(history.entries.map(\.text) == ["second"])
    }

    @Test func skipsItemWhoseMarkerIsAddedAfterTheText() {
        let monitor = makeMonitor()
        monitor.poll()
        pasteboard.copy("secret")
        pasteboard.whileReadingString = { $0.addMarker(PasteboardMarker.concealed) }
        monitor.poll()
        #expect(history.entries.isEmpty)
    }

    @Test func skipsItemsWithoutText() {
        let monitor = makeMonitor()
        pasteboard.copyImage()
        monitor.poll()
        #expect(history.entries.isEmpty)
    }

    @Test func skipsEmptyText() {
        let monitor = makeMonitor()
        pasteboard.copy("")
        monitor.poll()
        #expect(history.entries.isEmpty)
    }

    @Test func skipsTextOverSizeLimit() {
        let monitor = makeMonitor()
        pasteboard.copy(String(repeating: "a", count: ClipboardMonitor.maximumTextBytes + 1))
        monitor.poll()
        #expect(history.entries.isEmpty)

        pasteboard.copy(String(repeating: "a", count: ClipboardMonitor.maximumTextBytes))
        monitor.poll()
        #expect(history.entries.count == 1)
    }

    @Test func startRecordsImmediatelyAndStopEndsPolling() {
        let monitor = makeMonitor()
        pasteboard.copy("on start")
        monitor.start()
        #expect(monitor.isPolling)
        #expect(history.entries.map(\.text) == ["on start"])

        monitor.stop()
        #expect(!monitor.isPolling)
    }
}

@MainActor
struct ClipboardMonitorCurrentEntryTests {
    private let pasteboard = FakePasteboard()
    private let history = ClipboardHistory()

    private func makeMonitorWithRecordedEntry() -> ClipboardMonitor {
        let monitor = ClipboardMonitor(pasteboard: pasteboard, history: history, frontmostApp: { nil })
        pasteboard.copy("recorded")
        monitor.poll()
        return monitor
    }

    @Test func recordedCopyIsCurrent() {
        _ = makeMonitorWithRecordedEntry()
        #expect(history.currentEntryID != nil)
        #expect(history.currentEntryID == history.entries.first?.id)
    }

    @Test(arguments: [PasteboardMarker.concealed, PasteboardMarker.transient, PasteboardMarker.autoGenerated])
    func skippedMarkedCopyIsNotCurrent(marker: String) {
        let monitor = makeMonitorWithRecordedEntry()
        pasteboard.copy("secret", markers: [marker])
        monitor.poll()
        #expect(history.currentEntryID == nil)
    }

    @Test func skippedImageIsNotCurrent() {
        let monitor = makeMonitorWithRecordedEntry()
        pasteboard.copyImage()
        monitor.poll()
        #expect(history.currentEntryID == nil)
    }

    @Test func skippedEmptyTextIsNotCurrent() {
        let monitor = makeMonitorWithRecordedEntry()
        pasteboard.copy("")
        monitor.poll()
        #expect(history.currentEntryID == nil)
    }

    @Test func skippedLargeTextIsNotCurrent() {
        let monitor = makeMonitorWithRecordedEntry()
        pasteboard.copy(String(repeating: "a", count: ClipboardMonitor.maximumTextBytes + 1))
        monitor.poll()
        #expect(history.currentEntryID == nil)
    }

    @Test func unchangedPasteboardKeepsCurrentEntry() {
        let monitor = makeMonitorWithRecordedEntry()
        let currentID = history.currentEntryID
        monitor.poll()
        #expect(history.currentEntryID == currentID)
    }

    @Test func readThatIsRetriedKeepsCurrentEntryUntilTheRetry() {
        let monitor = makeMonitorWithRecordedEntry()
        let currentID = history.currentEntryID
        pasteboard.copy("first")
        pasteboard.whileReadingString = { $0.copy("secret", markers: [PasteboardMarker.concealed]) }
        monitor.poll()
        #expect(history.currentEntryID == currentID)

        monitor.poll()
        #expect(history.currentEntryID == nil)
    }
}

@MainActor
struct ClipboardMonitorPauseTests {
    private let pasteboard = FakePasteboard()
    private let history = ClipboardHistory()

    private func makeStartedMonitor() -> ClipboardMonitor {
        let monitor = ClipboardMonitor(pasteboard: pasteboard, history: history, frontmostApp: { nil })
        monitor.start()
        return monitor
    }

    @Test func pauseStopsPolling() {
        let monitor = makeStartedMonitor()
        monitor.pause(for: .systemSleep)
        #expect(!monitor.isPolling)
        monitor.stop()
    }

    @Test func resumesOnlyWhenEveryReasonIsCleared() {
        let monitor = makeStartedMonitor()
        monitor.pause(for: .displaySleep)
        monitor.pause(for: .screenLocked)

        monitor.resume(for: .displaySleep)
        #expect(!monitor.isPolling)

        monitor.resume(for: .screenLocked)
        #expect(monitor.isPolling)
        monitor.stop()
    }

    @Test func resumeChecksThePasteboardRightAway() {
        let monitor = makeStartedMonitor()
        monitor.pause(for: .screenLocked)
        pasteboard.copy("copied before unlock")

        monitor.resume(for: .screenLocked)
        #expect(history.entries.map(\.text) == ["copied before unlock"])
        monitor.stop()
    }

    @Test func copyFoundAfterAPauseHasNoSourceApp() throws {
        let notes = SourceApp(bundleIdentifier: "com.apple.Notes", name: "Notes")
        let monitor = ClipboardMonitor(pasteboard: pasteboard, history: history, frontmostApp: { notes })
        monitor.start()
        monitor.pause(for: .screenLocked)
        // Copied on another device or by a background app while the screen was locked.
        pasteboard.copy("copied while locked")

        monitor.resume(for: .screenLocked)
        let entry = try #require(history.entries.first)
        #expect(entry.text == "copied while locked")
        #expect(entry.sourceApp == nil)
        monitor.stop()
    }

    @Test func copyAfterTheFirstPollFollowingAPauseHasSourceApp() {
        let notes = SourceApp(bundleIdentifier: "com.apple.Notes", name: "Notes")
        let monitor = ClipboardMonitor(pasteboard: pasteboard, history: history, frontmostApp: { notes })
        monitor.start()
        monitor.pause(for: .systemSleep)
        monitor.resume(for: .systemSleep)

        pasteboard.copy("copied after wake")
        monitor.poll()
        #expect(history.entries.first?.sourceApp == notes)
        monitor.stop()
    }

    @Test func copyFoundAfterStopAndStartHasNoSourceApp() {
        let notes = SourceApp(bundleIdentifier: "com.apple.Notes", name: "Notes")
        let monitor = ClipboardMonitor(pasteboard: pasteboard, history: history, frontmostApp: { notes })
        monitor.start()
        monitor.stop()
        pasteboard.copy("copied while stopped")

        monitor.start()
        #expect(history.entries.first?.sourceApp == nil)
        monitor.stop()
    }

    @Test func pauseBeforeStartKeepsMonitorIdle() {
        let monitor = ClipboardMonitor(pasteboard: pasteboard, history: history, frontmostApp: { nil })
        monitor.pause(for: .systemSleep)
        monitor.start()
        #expect(!monitor.isPolling)

        monitor.resume(for: .systemSleep)
        #expect(monitor.isPolling)
        monitor.stop()
    }

    @Test func resumeWithoutStartDoesNotPoll() {
        let monitor = ClipboardMonitor(pasteboard: pasteboard, history: history, frontmostApp: { nil })
        monitor.pause(for: .systemSleep)
        monitor.resume(for: .systemSleep)
        #expect(!monitor.isPolling)
    }
}

/// Replaces `Task.sleep` in the polling loop. Each sleep lasts until the test calls `wakeAll()`.
@MainActor
final class ManualSleeper {
    private(set) var requestedDurations: [Duration] = []
    private var sleepers: [CheckedContinuation<Void, Never>] = []

    var sleepingCount: Int {
        sleepers.count
    }

    func sleep(for duration: Duration) async {
        requestedDurations.append(duration)
        await withCheckedContinuation { sleepers.append($0) }
    }

    func wakeAll() {
        let woken = sleepers
        sleepers.removeAll()
        for sleeper in woken {
            sleeper.resume()
        }
    }

    /// Lets other main-actor tasks run until the polling loop sleeps again. Does not wait for real time.
    func waitUntilSleeping() async {
        var turns = 0
        while sleepers.isEmpty, turns < 10_000 {
            turns += 1
            await Task.yield()
        }
    }

    /// Lets other main-actor tasks run for a while, for checks that nothing happens.
    func yieldForAWhile() async {
        for _ in 0..<100 {
            await Task.yield()
        }
    }
}

@MainActor
struct ClipboardMonitorPollingTests {
    private let pasteboard = FakePasteboard()
    private let history = ClipboardHistory()
    private let sleeper = ManualSleeper()

    private func makeMonitor() -> ClipboardMonitor {
        ClipboardMonitor(
            pasteboard: pasteboard,
            history: history,
            interval: .seconds(3),
            frontmostApp: { nil },
            sleep: { [sleeper] duration in await sleeper.sleep(for: duration) }
        )
    }

    @Test func pollingLoopPicksUpNewCopies() async {
        let monitor = makeMonitor()
        monitor.start()
        await sleeper.waitUntilSleeping()
        #expect(sleeper.requestedDurations == [.seconds(3)])

        pasteboard.copy("copied later")
        #expect(history.entries.isEmpty)

        sleeper.wakeAll()
        await sleeper.waitUntilSleeping()
        #expect(history.entries.map(\.text) == ["copied later"])
        #expect(sleeper.requestedDurations == [.seconds(3), .seconds(3)])

        monitor.stop()
        sleeper.wakeAll()
    }

    @Test func stoppedLoopDoesNotPollOrSleepAgain() async {
        let monitor = makeMonitor()
        monitor.start()
        await sleeper.waitUntilSleeping()

        monitor.stop()
        pasteboard.copy("copied after stop")
        sleeper.wakeAll()
        await sleeper.yieldForAWhile()

        #expect(history.entries.isEmpty)
        #expect(sleeper.sleepingCount == 0)
        #expect(sleeper.requestedDurations.count == 1)
    }
}

@MainActor
final class CountingActivity: PollingActivity {
    private(set) var beginCount = 0
    private(set) var endCount = 0

    var isActive: Bool {
        beginCount > endCount
    }

    func begin() {
        beginCount += 1
    }

    func end() {
        endCount += 1
    }
}

@MainActor
struct ClipboardMonitorActivityTests {
    private let pasteboard = FakePasteboard()
    private let history = ClipboardHistory()
    private let activity = CountingActivity()

    private func makeMonitor() -> ClipboardMonitor {
        ClipboardMonitor(pasteboard: pasteboard, history: history, frontmostApp: { nil }, activity: activity)
    }

    @Test func pollingHoldsTheActivityUntilStop() {
        let monitor = makeMonitor()
        #expect(!activity.isActive)

        monitor.start()
        monitor.start()
        #expect(activity.beginCount == 1)
        #expect(activity.isActive)

        monitor.stop()
        #expect(activity.endCount == 1)
        #expect(!activity.isActive)
    }

    @Test func pauseEndsTheActivityAndResumeBeginsItAgain() {
        let monitor = makeMonitor()
        monitor.start()
        monitor.pause(for: .screenLocked)
        monitor.pause(for: .displaySleep)
        #expect(!activity.isActive)
        #expect(activity.endCount == 1)

        monitor.resume(for: .screenLocked)
        #expect(!activity.isActive)
        monitor.resume(for: .displaySleep)
        #expect(activity.isActive)
        #expect(activity.beginCount == 2)
        monitor.stop()
    }

    @Test func pausedOrStoppedMonitorDoesNotBeginTheActivity() {
        let monitor = makeMonitor()
        monitor.pause(for: .systemSleep)
        monitor.start()
        monitor.stop()
        #expect(activity.beginCount == 0)
        #expect(activity.endCount == 0)
    }
}

import Foundation

/// Markers that apps put on the pasteboard to say how an item should be treated (see nspasteboard.org).
enum PasteboardMarker {
    /// Passwords and other secrets from password managers.
    static let concealed = "org.nspasteboard.ConcealedType"
    /// Items that are only on the pasteboard for a moment and should not be kept.
    static let transient = "org.nspasteboard.TransientType"
    /// Items an app put on the pasteboard without the user copying anything.
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    /// Older markers that some password managers and clipboard tools still use.
    static let legacy: Set<String> = [
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
    ]

    /// Items with any of these markers are not recorded. Concealed items will be stored masked and encrypted later.
    static let skipped: Set<String> = legacy.union([concealed, transient, autoGenerated])
}

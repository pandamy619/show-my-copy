import Foundation

/// Markers that apps put on the pasteboard to say how an item should be treated (see nspasteboard.org).
enum PasteboardMarker {
    /// Passwords and other secrets from password managers.
    static let concealed = "org.nspasteboard.ConcealedType"
    /// Items that are only on the pasteboard for a moment and should not be kept.
    static let transient = "org.nspasteboard.TransientType"
    /// Items an app put on the pasteboard without the user copying anything.
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    /// Holds the bundle identifier of the app that wrote the item. This app adds it to items it writes back.
    static let source = "org.nspasteboard.source"

    /// Older markers that password managers use instead of `concealed`.
    static let legacyPassword: Set<String> = [
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
    ]

    /// Older markers that clipboard and text tools use instead of `transient` or `autoGenerated`.
    static let legacyTransient: Set<String> = [
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Older markers that some password managers and clipboard tools still use.
    static let legacy: Set<String> = legacyPassword.union(legacyTransient)

    /// Passwords. They are kept, hidden and for a limited time, only when the user allows it in Settings.
    static let secret: Set<String> = legacyPassword.union([concealed])

    /// Items with any of these markers are never recorded. They are not passwords, just not meant to be kept.
    static let alwaysSkipped: Set<String> = legacyTransient.union([transient, autoGenerated])
}
